SELECT
    set_name,
    set_number,
    pieces,
    minifigs,
    age,
    theme_l1,
    theme_l2,
    theme_l3,
    brickset,
    released,
    DATE_PART('year',released)::INT AS year_released,
    DATE_TRUNC('month',released)::DATE AS month_released,
    availability,
    retail_gbp,
    retail_usd,
    retail_eur,
    ROUND(retail_gbp/big_mac_gbp, 1) AS bmc_gb,
    ROUND(retail_usd/big_mac_usd, 1) AS bmc_us,
    ROUND(retail_eur/big_mac_eur, 1) AS bmc_eu,
    ROUND(pieces/(retail_usd/big_mac_usd), 1) AS ppbm_us,
    ROUND(pieces/(retail_gbp/big_mac_gbp), 1) AS ppbm_gb,
    ROUND(pieces/(retail_eur/big_mac_eur), 1) AS ppbm_eu,
    ROUND(pieces/(retail_usd/sp500), 0) AS ppsp,
    ROUND(pieces/retail_gbp, 1) AS ppp,
    ROUND(pieces/retail_usd, 1) AS ppd,
    ROUND(pieces/retail_eur, 1) AS ppe

FROM {{ ref('int_lego__sp500_join') }}